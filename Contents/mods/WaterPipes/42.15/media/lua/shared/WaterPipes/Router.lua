WaterPipes = WaterPipes or {}
WaterPipes.Router = WaterPipes.Router or {}

require "WaterPipes/Constants"
require "WaterPipes/PipeObjectUtils"

local Constants = WaterPipes.Constants
local PipeObjectUtils = WaterPipes.PipeObjectUtils
local Router = WaterPipes.Router

-- A fluid router is a floor pipe flagged in modData. It is a network BOUNDARY: the graph and the
-- gravity traversal never conduct through it, so the IN-side pipes and OUT-side pipes stay two
-- separate networks. The active IN->container->OUT transfer (with the direction) lands in step 4.

local function getModData(worldObject)
    if not worldObject or not worldObject.getModData then
        return nil
    end
    local ok, modData = pcall(worldObject.getModData, worldObject)
    return ok and modData or nil
end

function Router.isRouter(worldObject)
    local modData = getModData(worldObject)
    return modData and modData[Constants.ROUTER_MODDATA_KEY] == true or false
end

-- Straight pipe with a green(IN)/red(OUT) band, keyed by the OUT direction (atlas cells 32-35,
-- generated by tools/texturepack/gen_pipes.py -- repack the .pack for these to render).
local DIR_SPRITE = {
    N = "waterpipes_01_32",
    E = "waterpipes_01_33",
    S = "waterpipes_01_34",
    W = "waterpipes_01_35",
}

function Router.spriteForDirection(dir)
    return DIR_SPRITE[dir] or Constants.ROUTER_SPRITE
end

function Router.spriteFor(worldObject)
    return Router.spriteForDirection(Router.getDirection(worldObject))
end

function Router.findOnSquare(square)
    if not square then
        return nil
    end
    for _, worldObject in ipairs(PipeObjectUtils.getPipeObjectsOnSquare(square)) do
        if Router.isRouter(worldObject) then
            return worldObject
        end
    end
    return nil
end

function Router.hasRouterOnSquare(square)
    return Router.findOnSquare(square) ~= nil
end

-- ===== Direction (IN -> OUT) =====
-- The stored direction is the OUT side. Isometric mapping matches PipeAutotile: N=-y, E=+x, S=+y, W=-x.
local DIR_OFFSET = {
    N = { dx = 0, dy = -1 },
    E = { dx = 1, dy = 0 },
    S = { dx = 0, dy = 1 },
    W = { dx = -1, dy = 0 },
}

local function isValidDirection(dir)
    return dir == "N" or dir == "E" or dir == "S" or dir == "W"
end

function Router.getDirection(worldObject)
    local modData = getModData(worldObject)
    local dir = modData and modData[Constants.ROUTER_DIRECTION_KEY]
    if isValidDirection(dir) then
        return dir
    end
    return Constants.ROUTER_DEFAULT_DIRECTION
end

-- {dx,dy} of the OUT side; the IN side is the opposite.
function Router.getOutOffset(worldObject)
    return DIR_OFFSET[Router.getDirection(worldObject)]
end

-- ===== Pressure regulation =====
-- A router already stops pressure crossing it, which makes it the one place a player can put a
-- ceiling on a zone. Set it from the context menu; the OUT-side zone then runs at
-- min(incoming head, ceiling). It can only ever REDUCE -- see Router.applyCeiling.

function Router.getPressureCeiling(worldObject)
    local modData = getModData(worldObject)
    local value = modData and modData[Constants.ROUTER_PRESSURE_KEY]
    if type(value) == "number" and value >= 0 then
        return value
    end
    return nil   -- unset: pass the incoming head straight through
end

function Router.setPressureCeiling(worldObject, value)
    local modData = getModData(worldObject)
    if not modData then
        return
    end
    if type(value) ~= "number" or value < 0 then
        modData[Constants.ROUTER_PRESSURE_KEY] = Constants.ROUTER_PRESSURE_UNSET
    else
        modData[Constants.ROUTER_PRESSURE_KEY] =
            math.min(math.max(value, 0), Constants.ROUTER_PRESSURE_MAX)
    end
    if worldObject.transmitModData then
        pcall(worldObject.transmitModData, worldObject)
    end
end

-- A reducing valve can only ever reduce. This one line is what stops a router from becoming a free
-- pump: set a router to 25 with 10 coming in and you still get 10, so pumps remain the only way to
-- CREATE head. Real pressure-reducing valves work exactly this way.
function Router.applyCeiling(head, ceiling)
    if not ceiling then
        return head
    end
    return math.min(head, ceiling)
end

-- The tightest ceiling imposed on a zone by the routers feeding INTO it, or nil if none do.
--
-- `boundaryRouters` are the routers the network walk bumped into (each { router, square }), so this
-- costs nothing but a lookup per boundary. A router regulates only what it PUSHES: we keep it when
-- its OUT side lands inside this zone, and ignore it when the zone sits on its IN side -- that zone
-- is upstream, and a reducing valve has no say over what feeds it.
function Router.ceilingForZone(boundaryRouters, pipeSquares)
    if not boundaryRouters or #boundaryRouters == 0 or not pipeSquares then
        return nil
    end

    local inZone = {}
    for _, square in ipairs(pipeSquares) do
        inZone[square:getX() .. ":" .. square:getY() .. ":" .. square:getZ()] = true
    end

    local tightest = nil
    for _, entry in ipairs(boundaryRouters) do
        local out = Router.getOutOffset(entry.router)
        local square = entry.square
        if out and square then
            local key = (square:getX() + out.dx) .. ":" .. (square:getY() + out.dy) .. ":" .. square:getZ()
            if inZone[key] then
                local ceiling = Router.getPressureCeiling(entry.router)
                if ceiling and (not tightest or ceiling < tightest) then
                    tightest = ceiling
                end
            end
        end
    end

    return tightest
end

return Router
